import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { http, HttpResponse } from 'msw'
import { renderApp } from './renderApp'
import { demoState, server } from './setup'
import { openTab, signIn } from './shell'
import { s4CaseId } from '../mocks/coordinator-state'

async function openNewCase(user: ReturnType<typeof userEvent.setup>) {
  await signIn(user)
  await user.click(await screen.findByRole('link', { name: 'Fiktivní pacient S4' }))
  await screen.findByRole('heading', { level: 1, name: 'Fiktivní pacient S4' })
  await user.click(screen.getByRole('button', { name: 'Převzít' }))
  await screen.findByText('V triage')
}
const dialog = () => screen.findByRole('dialog')
async function save(user: ReturnType<typeof userEvent.setup>) {
  await user.click(within(await dialog()).getByRole('button', { name: 'Uložit' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
}

describe('S4 coordinator screens', () => {
  it('takes over, edits case metadata, holds and resumes, then shows the immutable audit', async () => {
    renderApp(); const user = userEvent.setup(); await openNewCase(user)
    await user.click(screen.getByRole('button', { name: 'Upravit případ' }))
    let form = within(await dialog())
    await user.selectOptions(form.getByLabelText(/^Priorita/), 'urgent')
    await user.selectOptions(form.getByLabelText('MDT tým'), 'mdt-git-lipova')
    await user.type(form.getByLabelText('Plánované datum MDT'), '2026-10-25')
    await save(user)
    expect(screen.getByText('Urgentní')).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Odložit' }))
    form = within(await dialog())
    await user.type(form.getByLabelText(/^Důvod odložení/), 'Čeká na termín CT')
    await save(user)
    expect(screen.getByRole('button', { name: 'Obnovit' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Obnovit' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Odložit' })).toBeEnabled())
    const audit = await openTab(user, 'Audit')
    expect(await within(audit).findByText('Převzetí případu')).toBeVisible()
    expect(within(audit).getByText('Úprava případu')).toBeVisible()
    expect(within(audit).getByText('Obnovení')).toBeVisible()
    // Grouped under a day heading, newest first.
    expect(within(audit).getAllByRole('heading', { level: 3 })).toHaveLength(1)
    const events = within(audit).getAllByRole('listitem')
    expect(events[0]).toHaveTextContent('Obnovení')
    expect(events.at(-1)).toHaveTextContent('Převzetí případu')
  })

  it('fills a handover field without resolving its finding and requires an override reason', async () => {
    renderApp(); const user = userEvent.setup(); await openNewCase(user)
    await openTab(user, /^K řešení/)
    let issue = await screen.findByRole('article', { name: 'Fiktivní ukázka: chybí ECOG / Karnofsky.' })
    await user.click(within(issue).getByRole('button', { name: 'Doplnit' }))
    await user.type(within(await dialog()).getByLabelText(/^Hodnota/), 'ECOG 1')
    await save(user)
    expect(demoState.documents.result(s4CaseId)?.handover.performance_status).toMatchObject({ value: 'ECOG 1', origin: 'manual' })
    issue = screen.getByRole('article', { name: 'Fiktivní ukázka: chybí ECOG / Karnofsky.' })
    expect(within(issue).getByRole('button', { name: 'Uzavřít nález' })).toBeEnabled()
    await user.click(within(issue).getByRole('button', { name: 'Uzavřít nález' }))
    const form = within(await dialog())
    await user.selectOptions(form.getByLabelText(/^Způsob vyřešení/), 'overridden')
    await user.click(form.getByRole('button', { name: 'Uložit' }))
    expect(await form.findByRole('alert')).toBeVisible()
    await user.type(form.getByLabelText(/^Poznámka/), 'Údaj byl posouzen při triage.')
    await save(user)
    expect(demoState.documents.result(s4CaseId)?.findings.find((finding) => finding.id.endsWith('demo-missing'))?.resolution).toMatchObject({ kind: 'overridden', by: 'koordinator' })
    await user.click(screen.getByRole('button', { name: 'Vyřešené nálezy (1)' }))
    await waitFor(() => expect(screen.getByText('Údaj byl posouzen při triage.')).toBeVisible())
  })

  it('creates a request linked to its finding and returns the referral with a note', async () => {
    renderApp(); const user = userEvent.setup(); await openNewCase(user)
    await openTab(user, /^K řešení/)
    const issue = await screen.findByRole('article', { name: 'Fiktivní ukázka: vyžádejte chybějící zprávu.' })
    await user.click(within(issue).getByRole('button', { name: 'Vyžádat' }))
    await user.selectOptions(within(await dialog()).getByLabelText(/^Odpovědná osoba/), 'pl-reznicek')
    await save(user)
    const tasks = await openTab(user, 'Úkoly')
    expect(await within(tasks).findByText('Fiktivní ukázka: vyžádejte chybějící zprávu.')).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Vrátit lékaři' }))
    const form = within(await dialog())
    await user.type(form.getByLabelText(/^Poznámka/), 'Prosím o doplnění podkladů.')
    await user.click(form.getByRole('button', { name: 'Vrátit lékaři' }))
    await screen.findByText('Vráceno lékaři')
    expect(demoState.coordinator.messages(s4CaseId)[0].body).toBe('Prosím o doplnění podkladů.')
  })

  it('creates and edits a task, then navigates from its personal deadline notification to the task', async () => {
    const { router } = renderApp(); const user = userEvent.setup(); await openNewCase(user)
    await openTab(user, 'Úkoly')
    await user.click(screen.getByRole('button', { name: 'Přidat úkol' }))
    const form = within(await dialog())
    await user.type(form.getByLabelText(/^Název/), 'Telefonicky ověřit termín')
    await user.type(form.getByLabelText('Datum a čas termínu'), '2026-10-21T14:00')
    await save(user)
    await user.click(screen.getByRole('button', { name: 'Upravit úkol' }))
    await user.selectOptions(within(await dialog()).getByLabelText(/^Stav úkolu/), 'booked')
    await user.selectOptions(within(await dialog()).getByLabelText('Výsledný dokument'), `${s4CaseId}-document`)
    await save(user)
    expect(await screen.findByText('Objednáno')).toBeVisible()
    await user.click(screen.getByRole('link', { name: 'Zpět na pracovní frontu' }))
    await user.click(await screen.findByRole('button', { name: 'Notifikace' }))
    await user.click(await screen.findByRole('link', { name: 'Telefonicky ověřit termín' }))
    await waitFor(() => expect(router.state.location).toMatchObject({ pathname: '/coordinator/cases/demo-s4', search: { tab: 'tasks' } }))
    expect(router.state.location.hash).toMatch(/^task-demo-task-/)
  })

  it('keeps a task draft after an API error, retries, and returns focus when a dialog closes on Escape', async () => {
    renderApp('/', { notifications: true }); const user = userEvent.setup(); await openNewCase(user)
    await openTab(user, 'Úkoly')
    const trigger = screen.getByRole('button', { name: 'Přidat úkol' })
    await user.click(trigger)
    await user.keyboard('{Escape}')
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    await waitFor(() => expect(trigger).toHaveFocus())
    await user.click(trigger)
    const form = within(await dialog())
    await user.type(form.getByLabelText(/^Název/), 'Zachovaný koncept úkolu')
    server.use(http.post('*/api/cases/:caseId/tasks', () => HttpResponse.json({ detail: 'temporary failure' }, { status: 500 }), { once: true }))
    await user.click(form.getByRole('button', { name: 'Uložit' }))
    expect(await screen.findByText('Při zpracování požadavku nastala chyba. Zkuste to znovu.')).toBeVisible()
    expect(form.getByRole('button', { name: 'Uložit' }).closest('[data-notification]')).toBeNull()
    expect(form.getByLabelText(/^Název/)).toHaveValue('Zachovaný koncept úkolu')
    await save(user)
    expect(await within(screen.getByRole('tabpanel', { name: 'Úkoly' })).findByText('Zachovaný koncept úkolu')).toBeVisible()
  })

  it('creates a reusable task set and starts it with explicit role assignment in a single dialog', async () => {
    renderApp(); const user = userEvent.setup(); await openNewCase(user)
    await openTab(user, 'Úkoly')
    await user.click(screen.getByRole('button', { name: 'Spustit sadu úkolů' }))
    await user.click(within(await dialog()).getByRole('button', { name: 'Vytvořit sadu' }))
    let form = within(await dialog())
    await user.type(form.getByLabelText(/^Název sady/), 'S4 kontrolní sada')
    await user.type(form.getByLabelText(/^Název\s*\*/), 'Ověření výsledků')
    await user.click(form.getByRole('button', { name: 'Uložit' }))
    const card = await screen.findByRole('article', { name: 'S4 kontrolní sada' })
    await user.click(within(card).getByRole('button', { name: 'Spustit sadu úkolů' }))
    form = within(await dialog())
    await user.selectOptions(form.getByLabelText(/^Přiřazení:/), 'koordinator')
    await user.click(form.getByRole('button', { name: 'Spustit sadu úkolů' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(await within(screen.getByRole('tabpanel', { name: 'Úkoly' })).findByText('Ověření výsledků')).toBeVisible()
  })
})
