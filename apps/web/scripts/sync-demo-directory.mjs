// S1 fixtures are serialized with the defaults of the committed API schema.
// Clinical text and original bytes always come from the canonical data files.
const dataRoot = new URL('../../../data/', import.meta.url)
const spec = JSON.parse(await readFile(new URL('../openapi.json', import.meta.url), 'utf8'))
function normalize(value, schema) {
  if (schema.$ref) return normalize(value, spec.components.schemas[schema.$ref.split('/').at(-1)])
  if (schema.anyOf && value !== null) return normalize(value, schema.anyOf.find((item) => item.type !== 'null'))
  if (Array.isArray(value)) return value.map((item) => normalize(item, schema.items))
  if (value && typeof value === 'object' && schema.properties) {
    const result = { ...value }
    for (const [name, property] of Object.entries(schema.properties)) {
      if (!(name in result) && 'default' in property) result[name] = structuredClone(property.default)
      if (name in result) result[name] = normalize(result[name], property)
    }
    return result
  }
  return value
}
const readJson = async (name) => JSON.parse(await readFile(new URL(`vzp-structured/reference/${name}.json`, dataRoot), 'utf8'))
const handover = normalize(await readJson('expected_handover'), spec.components.schemas.Handover)
const findings = (await readJson('expected_findings')).map((item) => normalize(item, spec.components.schemas.Finding))
const documents = (await readJson('manifest')).filter((item) => item.received_at.slice(0, 10) <= handover.as_of).map((item) => normalize({
  ...item, case_id: handover.case_id, uploaded_by: item.id === '07' ? 'pl-reznicek' : 'koordinator',
  mime_type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
}, spec.components.schemas.DocumentMeta))
const texts = {}, originals = {}
for (const document of documents) {
  texts[document.id] = await readFile(new URL(`vzp-structured/reports/${document.filename.replace(/\.docx$/, '.md')}`, dataRoot), 'utf8')
  originals[document.id] = (await readFile(new URL(`cesta-pacienta-data/Pacient/${document.filename}`, dataRoot))).toString('base64')
}
await writeFile(new URL('../src/mocks/reference-data.ts', import.meta.url),
  `// Generated by npm run sync:demo from canonical reference data and OpenAPI defaults.\nimport type { DocumentMeta, Finding, Handover } from '../client/types.gen'\n\n` +
  `export const referenceHandover: Handover = ${JSON.stringify(handover, null, 2)}\n\n` +
  `export const referenceFindings: Finding[] = ${JSON.stringify(findings, null, 2)}\n\n` +
  `export const referenceDocuments: DocumentMeta[] = ${JSON.stringify(documents, null, 2)}\n\n` +
  `export const referenceTexts: Record<string, string> = ${JSON.stringify(texts, null, 2)}\n`)
await writeFile(new URL('../src/mocks/document-files.ts', import.meta.url),
  `// Generated by npm run sync:demo. Exact original DOCX bytes, base64 encoded.\nexport const originalFiles: Record<string, string> = ${JSON.stringify(originals, null, 2)}\n`)
